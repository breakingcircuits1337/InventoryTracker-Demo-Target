package com.acme.inventory.dao;

import com.acme.inventory.model.Product;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;

import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Contract tests for {@link ProductDao} — Module 2, L2L[VERIFY].
 *
 * Uses an in-memory H2 database; no Spring context is started.
 * Covers contracts PD-01 through PD-07.
 */
class ProductDaoContractTest {

    private ProductDao dao;
    private JdbcTemplate jdbc;

    @BeforeEach
    void setUp() {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:test_dao_" + System.nanoTime() + ";DB_CLOSE_DELAY=-1");
        ds.setUser("sa");
        ds.setPassword("");

        jdbc = new JdbcTemplate(ds);

        // Create schema
        jdbc.execute(
            "CREATE TABLE products (" +
            "  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY," +
            "  sku              VARCHAR(50)  NOT NULL," +
            "  name             VARCHAR(200) NOT NULL," +
            "  description      VARCHAR(500)," +
            "  category         VARCHAR(100)," +
            "  unit_price       DOUBLE       NOT NULL DEFAULT 0," +
            "  quantity_on_hand INT          NOT NULL DEFAULT 0," +
            "  reorder_point    INT          NOT NULL DEFAULT 0," +
            "  supplier_code    VARCHAR(50)," +
            "  active           INT          NOT NULL DEFAULT 1," +
            "  last_updated     TIMESTAMP" +
            ")"
        );

        dao = new ProductDao();
        // Inject JdbcTemplate via reflection (field injection used in source)
        try {
            java.lang.reflect.Field f = ProductDao.class.getDeclaredField("jdbcTemplate");
            f.setAccessible(true);
            f.set(dao, jdbc);
        } catch (Exception e) {
            throw new RuntimeException(e);
        }
    }

    // ------------------------------------------------------------------
    // helpers
    // ------------------------------------------------------------------

    private Product insertActive(String sku, String name, String category, int qty, int reorder) {
        jdbc.update(
            "INSERT INTO products (sku, name, category, unit_price, quantity_on_hand, reorder_point, active) " +
            "VALUES (?,?,?,?,?,?,1)",
            sku, name, category, 9.99, qty, reorder
        );
        Long id = jdbc.queryForObject("SELECT MAX(id) FROM products", Long.class);
        Product p = new Product();
        p.setId(id);
        p.setSku(sku);
        p.setName(name);
        p.setCategory(category);
        p.setUnitPrice(9.99);
        p.setQuantityOnHand(qty);
        p.setReorderPoint(reorder);
        p.setActive(true);
        return p;
    }

    private void insertInactive(String sku, String name, String category) {
        jdbc.update(
            "INSERT INTO products (sku, name, category, unit_price, quantity_on_hand, reorder_point, active) " +
            "VALUES (?,?,?,?,?,?,0)",
            sku, name, category, 1.00, 0, 0
        );
    }

    // ------------------------------------------------------------------
    // PD-01  findAll returns only active rows, ordered by name
    // ------------------------------------------------------------------

    @Test
    void findAll_returnsOnlyActiveProducts() {
        insertActive("A01", "Bolt", "Hardware", 50, 10);
        insertActive("A02", "Nut",  "Hardware", 30, 5);
        insertInactive("A03", "Ghost", "Hardware");

        List<Product> result = dao.findAll();

        assertEquals(2, result.size());
        assertTrue(result.stream().allMatch(Product::isActive));
    }

    @Test
    void findAll_orderedByName() {
        insertActive("Z01", "Zebra Widget", "Misc", 1, 0);
        insertActive("A01", "Alpha Widget", "Misc", 1, 0);

        List<Product> result = dao.findAll();

        assertEquals("Alpha Widget", result.get(0).getName());
        assertEquals("Zebra Widget", result.get(1).getName());
    }

    // ------------------------------------------------------------------
    // PD-02  findById returns null for missing / inactive
    // ------------------------------------------------------------------

    @Test
    void findById_knownActiveProduct_returnsProduct() {
        Product inserted = insertActive("B01", "Bracket", "Metal", 10, 2);

        Product found = dao.findById(inserted.getId());

        assertNotNull(found);
        assertEquals("B01", found.getSku());
    }

    @Test
    void findById_unknownId_returnsNull() {
        assertNull(dao.findById(999999L));
    }

    @Test
    void findById_inactiveProduct_returnsNull() {
        insertInactive("X01", "Discontinued", "Old");
        Long id = jdbc.queryForObject("SELECT MAX(id) FROM products", Long.class);

        assertNull(dao.findById(id));
    }

    // ------------------------------------------------------------------
    // PD-03  findByCategory returns only active rows in category
    // ------------------------------------------------------------------

    @Test
    void findByCategory_returnsOnlyMatchingActiveProducts() {
        insertActive("C01", "Cable",   "Electric", 20, 5);
        insertActive("C02", "Conduit", "Electric", 10, 2);
        insertActive("D01", "Drill",   "Tools",    5,  1);
        insertInactive("C99", "OldCable", "Electric");

        List<Product> result = dao.findByCategory("Electric");

        assertEquals(2, result.size());
        assertTrue(result.stream().allMatch(p -> "Electric".equals(p.getCategory())));
        assertTrue(result.stream().allMatch(Product::isActive));
    }

    @Test
    void findByCategory_noMatch_returnsEmptyList() {
        List<Product> result = dao.findByCategory("Nonexistent");
        assertTrue(result.isEmpty());
    }

    // ------------------------------------------------------------------
    // PD-04  save with id==null inserts a new row (row-count 1)
    // ------------------------------------------------------------------

    @Test
    void save_newProduct_insertsRow() {
        Product p = new Product();
        p.setSku("NEW01");
        p.setName("New Screw");
        p.setDescription("A fine screw");
        p.setCategory("Fasteners");
        p.setUnitPrice(0.05);
        p.setQuantityOnHand(1000);
        p.setReorderPoint(200);
        p.setSupplierCode("SUP-A");

        int rows = dao.save(p);

        assertEquals(1, rows);
        Integer count = jdbc.queryForObject(
            "SELECT COUNT(*) FROM products WHERE sku='NEW01' AND active=1", Integer.class);
        assertEquals(1, count);
    }

    // ------------------------------------------------------------------
    // PD-05  save with id!=null updates the existing row (row-count 1)
    // ------------------------------------------------------------------

    @Test
    void save_existingProduct_updatesRow() {
        Product inserted = insertActive("U01", "Old Name", "Tools", 5, 1);

        inserted.setName("New Name");
        inserted.setQuantityOnHand(99);

        int rows = dao.save(inserted);

        assertEquals(1, rows);
        String name = jdbc.queryForObject(
            "SELECT name FROM products WHERE id=?", String.class, inserted.getId());
        assertEquals("New Name", name);
        Integer qty = jdbc.queryForObject(
            "SELECT quantity_on_hand FROM products WHERE id=?", Integer.class, inserted.getId());
        assertEquals(99, qty);
    }

    // ------------------------------------------------------------------
    // PD-06  deactivate sets active=0; row still exists
    // ------------------------------------------------------------------

    @Test
    void deactivate_setsActiveToZero_rowStillExists() {
        Product inserted = insertActive("DEL01", "Deletable", "Misc", 1, 0);

        int rows = dao.deactivate(inserted.getId());

        assertEquals(1, rows);
        Integer active = jdbc.queryForObject(
            "SELECT active FROM products WHERE id=?", Integer.class, inserted.getId());
        assertEquals(0, active);
    }

    @Test
    void deactivate_afterDeactivation_findByIdReturnsNull() {
        Product inserted = insertActive("DEL02", "AlsoGone", "Misc", 1, 0);
        dao.deactivate(inserted.getId());

        assertNull(dao.findById(inserted.getId()));
    }

    // ------------------------------------------------------------------
    // PD-07  findAllCategories returns distinct ordered strings
    // ------------------------------------------------------------------

    @Test
    void findAllCategories_returnsDistinctOrderedStrings() {
        insertActive("E01", "Elbow", "Plumbing", 5, 1);
        insertActive("E02", "Elbow2", "Plumbing", 5, 1); // duplicate category
        insertActive("F01", "Fitting", "Electrical", 3, 1);
        insertInactive("G01", "Ghost", "Ghostly"); // inactive — must be excluded

        List<String> cats = dao.findAllCategories();

        assertEquals(2, cats.size());
        assertEquals("Electrical", cats.get(0));
        assertEquals("Plumbing", cats.get(1));
    }

    @Test
    void findAllCategories_emptyTable_returnsEmptyList() {
        List<String> cats = dao.findAllCategories();
        assertTrue(cats.isEmpty());
    }
}
